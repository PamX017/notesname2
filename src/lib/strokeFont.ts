/**
 * A tiny single-stroke cursive "font".
 *
 * Every glyph is ONE continuous pen stroke described by control points in glyph
 * units: x runs right, y runs up, baseline = 0, x-height = 1, ascender = 2,
 * descender = -1. The stroke implicitly starts at (0, 0) and the last point is
 * always (w, 0), so glyphs connect to each other like joined-up handwriting.
 */
export type Pt = [number, number];

export interface Glyph {
  /** advance width */
  w: number;
  /** control points after the implicit start (0,0); last must be (w,0) */
  pts: Pt[];
}

